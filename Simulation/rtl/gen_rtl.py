"""Generate cnn74_top.v: a flat structural Verilog netlist from output/top.net.

Everything that carries signal is preserved:

  * every 74xx / memory package becomes one instance of its behavioural model,
    connected by the exact KiCad pin numbers from analysis/pins.json;
  * every net becomes one Verilog wire (rails become 1'b1 / 1'b0);
  * 10k/100k pull resistors become pullup/pulldown primitives;
  * the 33R clock resistor and the 470R LED resistors become assigns;
  * the 8-resistor networks become eight pulls on their common rail;
  * the fitted JP1 1-2 shunt is modelled as OSC_OUT -> CLK_SEL (the netlist
    itself cannot contain a jumper shunt, so this is the one explicit
    board-level assumption).

Passives with no logic role (decoupling caps, LEDs, test points, connectors,
power flags) are dropped, as is the push button (the testbench drives
RESET_RAW directly).

Run:
    python gen_rtl.py
"""
from __future__ import annotations

import csv
import json
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.abspath(os.path.join(HERE, ".."))
ANALYSIS = os.path.join(SIM, "analysis")
PROJ = os.path.abspath(os.path.join(SIM, "..", "Cache", "CNN_74xx_System"))
sys.path.insert(0, ANALYSIS)

import build_analysis as ba  # noqa: E402  (parses output/top.net on import)

OUT = os.path.join(HERE, "cnn74_top.v")
MAP = os.path.join(HERE, "instance_map.csv")

RAILS = {"+5V": "1'b1", "+3V3": "1'b1", "GND": "1'b0"}
SKIP_PARTS = {"C", "LED", "TestPoint", "PWR_FLAG", "SW_Push"}
MODEL_PORTS = json.load(open(os.path.join(HERE, "model_ports.json"),
                             encoding="utf-8"))

INIT_DIR = os.path.join(HERE, "init")
os.makedirs(INIT_DIR, exist_ok=True)
MEM_INIT = {}
with open(os.path.join(ANALYSIS, "memories.csv"), encoding="utf-8-sig",
          newline="") as f:
    for row in csv.DictReader(f):
        MEM_INIT[row["ref"]] = row["init_file"]


def rom_init(ref: str) -> str | None:
    """Copy the image into rtl/init and return the parameter string."""
    src = MEM_INIT.get(ref, "")
    if ref == "U2001":
        return "init/timing.hex"      # reconstructed, see gen_timing_rom.py
    if not src or not src.startswith("model/"):
        return None
    stem = os.path.splitext(os.path.basename(src))[0]
    base = stem + ".hex"
    dst = os.path.join(INIT_DIR, base)
    # Always refresh: the images are regenerated by the microcode/LUT
    # generators and a stale copy silently simulates the wrong firmware.
    shutil.copyfile(os.path.join(PROJ, os.path.dirname(src), base), dst)
    return f"init/{base}"


def natural_key(s: str):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def is_connector(part: str) -> bool:
    return part.startswith("Conn_") or part.startswith("Connector")


# ---------------------------------------------------------------- net names
ident_by_name = {}
with open(os.path.join(ANALYSIS, "nets.csv"), encoding="utf-8-sig",
          newline="") as f:
    for row in csv.DictReader(f):
        ident_by_name[row["kicad_name"]] = row["verilog_ident"]

nets_by_name = {n["name"]: n for n in ba.NET}

# Friendly names for the nets the testbench drives or observes.
OVERRIDE = {}
PORT_IN = []
PORT_INOUT = []
PORT_OUT = []

# Host address bits 0..15 are real connector inputs.  Bits 16..23 became
# on-board tag bits derived from MEM_SEL (V1 fix), so they are no longer
# external ports.
for i in range(16):
    hit = [n for n in nets_by_name if n.endswith(f"/H_A{i}")]
    if len(hit) != 1:
        raise SystemExit(f"H_A{i}: expected 1 net, got {hit}")
    OVERRIDE[hit[0]] = f"H_A{i}"
    PORT_IN.append(f"H_A{i}")
for i in range(8):
    hit = [n for n in nets_by_name if n.endswith(f"/H_D{i}")]
    if len(hit) != 1:
        raise SystemExit(f"H_D{i}: expected 1 net, got {hit}")
    OVERRIDE[hit[0]] = f"H_D{i}"
    PORT_INOUT.append(f"H_D{i}")
for i in range(5):
    hit = [n for n in nets_by_name if n.endswith(f"/H_MEM_SEL{i}")]
    if len(hit) != 1:
        raise SystemExit(f"H_MEM_SEL{i}: expected 1 net, got {hit}")
    OVERRIDE[hit[0]] = f"H_MEM_SEL{i}"
    PORT_IN.append(f"H_MEM_SEL{i}")
for suffix in ("H_LOAD_nOE", "H_LOAD_nWE"):
    hit = [n for n in nets_by_name if n.endswith("/" + suffix)]
    if len(hit) != 1:
        raise SystemExit(f"{suffix}: expected 1 net, got {hit}")
    OVERRIDE[hit[0]] = suffix
    PORT_IN.append(suffix)
for n in ("START_RAW", "RESET_RAW"):
    full = f"/B12_S10_Top_IO/{n}"
    if full not in nets_by_name:
        raise SystemExit(f"missing host net {full}")
    OVERRIDE[full] = n
    PORT_IN.append(n)
for n in ("LOAD_EN", "IMAGE_DONE_N", "MODEL_DONE_N"):
    if n not in nets_by_name:
        raise SystemExit(f"missing global net {n}")
    OVERRIDE[n] = n
    PORT_IN.append(n)
for n in ("BUSY", "DONE", "RESULT_VALID", "ERROR",
          "RESULT0", "RESULT1", "RESULT2", "RESULT3",
          "ERROR_CODE0", "ERROR_CODE1", "ERROR_CODE2", "ERROR_CODE3",
          "IMAGE_READY", "MODEL_READY"):
    if n not in nets_by_name:
        raise SystemExit(f"missing global net {n}")
    OVERRIDE[n] = n
    PORT_OUT.append(n)


def net_ident(name: str) -> str:
    return OVERRIDE.get(name, ident_by_name[name])


def net_expr(name: str) -> str:
    if name in RAILS:
        return RAILS[name]
    return net_ident(name)


DRIVER_TYPES = {"output", "tri_state", "bidirectional", "open_collector",
                "power_out"}


def net_has_driver(name: str) -> bool:
    for node in nets_by_name[name]["nodes"]:
        if set((node["pintype"] or "").split("+")) & DRIVER_TYPES:
            return True
    return False


used_nets = set()


def use(name: str) -> None:
    if name not in RAILS:
        used_nets.add(name)


def model_module(lib: str, part: str) -> str:
    return "m_" + f"{lib}_{part}".replace("-", "_")


lines = []
map_rows = []
skipped = {"passive": 0, "connector": 0, "switch": 0}

for ref in sorted(ba.COMP, key=natural_key):
    c = ba.COMP[ref]
    lib, part = c["lib"], c["part"]
    full = f"{lib}:{part}"
    pins = ba.PIN_NET.get(ref, {})

    if part == "R":
        a, b = pins.get("1"), pins.get("2")
        if a is None or b is None:
            skipped["passive"] += 1
            continue
        if a.startswith("unconnected-") or b.startswith("unconnected-"):
            skipped["passive"] += 1
            continue
        ra, rb = a in RAILS, b in RAILS
        if ra and rb:
            skipped["passive"] += 1
            continue
        if ra or rb:
            rail, sig = (a, b) if ra else (b, a)
            use(sig)
            prim = "pullup" if RAILS[rail] == "1'b1" else "pulldown"
            lines.append(f"  {prim} ({net_ident(sig)});   // {ref} {c['value']}")
            map_rows.append([ref, "pull", f"{rail}->{sig}", c["sheet"]])
        else:
            use(a)
            use(b)
            # A resistor is bilateral, but Verilog assign is not: drive the
            # undriven side from the side that has a real output pin.
            drv_a = net_has_driver(a)
            drv_b = net_has_driver(b)
            if drv_b and not drv_a:
                src, dst = b, a
            else:
                src, dst = a, b
            lines.append(f"  assign {net_ident(dst)} = {net_ident(src)};"
                         f"   // {ref} {c['value']} series")
            map_rows.append([ref, "series", f"{src}->{dst}", c["sheet"]])
        continue

    if part == "R_Network08":
        common = pins.get("1")
        if common not in RAILS:
            raise SystemExit(f"{ref}: network common is {common}, not a rail")
        prim = "pullup" if RAILS[common] == "1'b1" else "pulldown"
        for num in range(2, 10):
            sig = pins.get(str(num))
            if not sig or sig.startswith("unconnected-"):
                continue
            use(sig)
            lines.append(f"  {prim} ({net_ident(sig)});   // {ref}.{num}")
            map_rows.append([ref, "pull", f"{common}->{sig}", c["sheet"]])
        continue

    if part in SKIP_PARTS:
        skipped["passive"] += 1
        continue

    if is_connector(part):
        if ref == "JP10001":
            n1, n2 = pins.get("1"), pins.get("2")
            if not n1 or not n2:
                raise SystemExit("JP10001 missing pins 1/2")
            use(n1)
            use(n2)
            lines.append(f"  assign {net_ident(n2)} = {net_ident(n1)};"
                         f"   // {ref}: fitted 1-2 shunt (internal osc)")
            map_rows.append([ref, "jumper", f"{n1}->{n2}", c["sheet"]])
        else:
            skipped["connector"] += 1
        continue

    if full not in MODEL_PORTS:
        raise SystemExit(f"{ref}: no model for {full}")

    ports = MODEL_PORTS[full]
    conns = []
    for pn in ports:
        net = pins.get(str(pn))
        if net is None or net.startswith("unconnected-"):
            continue
        use(net)
        conns.append(f".p{pn}({net_expr(net)})")
    param = ""
    if full == "Memory_EPROM:27C512":
        init = rom_init(ref)
        if init:
            param = f' #(.INIT("{init}"))'
    lines.append(f"  {model_module(lib, part)}{param} {ref} ("
                 + ", ".join(conns) + ");")
    map_rows.append([ref, full, part, c["sheet"]])

wires = sorted((net_ident(n) for n in used_nets if n not in OVERRIDE),
               key=lambda n: (n.lower(), n))

header = [
    "// Generated by gen_rtl.py - do not edit by hand.",
    "// Flat structural model of the 12-board CNN_74xx_System.",
    f"// Source netlist: {os.path.join(PROJ, 'output', 'top.net')}",
    f"// Packages: {len(map_rows)}  nets used: {len(used_nets)}  "
    f"wires: {len(wires)}",
    "`timescale 1ns/1ps",
    "",
    "module cnn74_top (",
]
port_lines = []
for n in PORT_IN:
    port_lines.append(f"  input  {n}")
for n in PORT_INOUT:
    port_lines.append(f"  inout  {n}")
for n in PORT_OUT:
    port_lines.append(f"  output {n}")
header.append(",\n".join(port_lines))
header.append(");")
header.append("")

body = ["  // ---- net declarations ----"]
body += [f"  wire {w};" for w in wires]
body.append("")
body.append("  // ---- pull networks, series resistors, fitted jumper ----")
body.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(header) + "\n")
    f.write("\n".join(body) + "\n")
    f.write("\n".join(lines) + "\n")
    f.write("endmodule\n")

with open(MAP, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f, lineterminator="\n")
    w.writerow(["ref", "model", "connection", "sheet"])
    w.writerows(map_rows)

print(f"wrote {OUT}")
print(f"  instances/pulls: {len(map_rows)}")
print(f"  nets used: {len(used_nets)}  wires: {len(wires)}")
print(f"  skipped: {skipped}")
